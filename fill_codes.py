def main():
    print(f"Загружаем: {INPUT_FILE}")
    wb = openpyxl.load_workbook(INPUT_FILE)
    ws = wb['Лист 1']

    rows = list(ws.iter_rows(values_only=True))
    print(f"Всего строк: {len(rows)}")

    filled_count = 0
    unchanged_count = 0
    manual_check = []

    for row_idx in range(2, len(rows) + 1):  # пропускаем строку 1 (заголовок)
        row = rows[row_idx - 1]
        if all(c is None for c in row):
            continue

        code_c = row[2]  # столбец C
        name_d = row[3]  # столбец D
        num_b = row[1]   # столбец B

        # Если C уже заполнен — не трогаем
        if code_c is not None and str(code_c).strip() != "":
            unchanged_count += 1
            continue

        # Строка без наименования — пропускаем
        if name_d is None or str(name_d).strip() == "":
            continue

        code = map_code(str(name_d), str(num_b) if num_b else "")

        if code:
            ws.cell(row=row_idx, column=3).value = code
            filled_count += 1
            print(f"  Стр.{row_idx}: '{str(name_d)[:55]}' → {code}")
        else:
            manual_check.append((row_idx, str(name_d)[:80], str(num_b) if num_b else ""))

    print(f"\n{'='*60}")
    print(f"Заполнено новых кодов: {filled_count}")
    print(f"Уже были заполнены:   {unchanged_count}")
    print(f"Требуют ручной проверки: {len(manual_check)}")

    if manual_check:
        print(f"\nСтроки без кода ({len(manual_check)} шт.):")
        for row_idx, name, num in manual_check:
            print(f"  Стр.{row_idx} ({num}): {name}")

    wb.save(OUTPUT_FILE)
    print(f"\nСохранено в: {OUTPUT_FILE}")


if __name__ == "__main__":
    main()
